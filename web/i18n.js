const I18N = {
  lang: 'en',
  missing: [],          // keys requested but absent from the active/en catalog
  onLangChange: null,   // registered by app.js: re-render in place (no reload)
  catalogs: { en: I18N_EN, zh: I18N_ZH },
};

// detectLang resolves the UI language: localStorage "grayling_lang" (explicit
// user choice) > navigator.language (zh* → zh) > en.
function detectLang() {
  try {
    const stored = typeof localStorage !== 'undefined' && localStorage.getItem('grayling_lang');
    if (stored === 'en' || stored === 'zh') return stored;
  } catch { /* storage unavailable (private mode / vm) */ }
  const nav = (typeof navigator !== 'undefined' && navigator.language) || '';
  return String(nav).toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

// t returns the catalog string for key in the active language, interpolating
// {name} placeholders from params. Gaps fall back to en and are recorded
// (console.warn + I18N.missing) so tests can assert zero missing keys.
function t(key, params) {
  const cat = I18N.catalogs[I18N.lang] || I18N_EN;
  let s = cat[key];
  if (s === undefined || !Object.prototype.hasOwnProperty.call(cat, key)) {
    if (I18N.missing.indexOf(key) < 0) I18N.missing.push(key);
    if (typeof console !== 'undefined' && console.warn) {
      console.warn('[i18n] missing key in "' + I18N.lang + '" catalog: ' + key);
    }
    s = I18N_EN[key];
    if (s === undefined) return key;
  }
  if (params) {
    s = s.replace(/\{(\w+)\}/g, (m0, name) =>
      Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : m0);
  }
  return s;
}

// setLang switches the UI language, persists the choice and lets app.js
// re-render the current view + chrome in place (no page reload).
function setLang(lang) {
  if (lang !== 'en' && lang !== 'zh') return;
  I18N.lang = lang;
  try {
    if (typeof localStorage !== 'undefined') localStorage.setItem('grayling_lang', lang);
  } catch { /* storage unavailable */ }
  if (typeof I18N.onLangChange === 'function') I18N.onLangChange();
}

// localeFor maps the active language to a BCP-47 locale for date formatting.
function localeFor() { return I18N.lang === 'zh' ? 'zh-CN' : 'en-US'; }

I18N.lang = detectLang();
